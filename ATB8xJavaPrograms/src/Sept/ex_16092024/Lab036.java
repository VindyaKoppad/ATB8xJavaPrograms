package Sept.ex_16092024;

public class Lab036 {

	public static void main(String[] args) {
		// Compound assignment operator
		//+=, -=, *=, /=
		int a=10;
		a+=20;
		System.out.println(a);//a=a+20
		
		a-=20;
		System.out.println(a);//a=a-20 
		
		a*=10;
		System.out.println(a);//a=a*10
		
		a/=20;
		System.out.println(a);//a=a/10

		
	}

}
