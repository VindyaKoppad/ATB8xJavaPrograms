package Sept.ex_16092024;

public class Lab031 {

	public static void main(String[] args) {
		//Binary operator 
		//Arithmatic operator = +,-,*,/,%(modulus)
		
		int a=10;
		int b=3;
		
		System.out.println(a+b);//Addition(SUM)
		System.out.println(a-b);//Subtraction(Difference)
		System.out.println(a*b);//Multiplication(Product)
		System.out.println(a/b);//Division(Quotient)
		
		//%- Modulus operator- which gives remainder
		System.out.println(a%b);
		
		
	}

}
