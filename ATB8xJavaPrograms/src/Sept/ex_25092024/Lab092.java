package Sept.ex_25092024;

public class Lab092 {
public static void main(String[] args) {
	//Loops
	/*1.For loop
	 * 2.While loop
	 * 3.Do-While loop
	*/
	
	
	//1.For Loop
	/*For- is a keyword
	 * it has 3 parts(A;B;c)
	 * A->Initialization
	 * B->Condition for termination
	 * C->Increment/Decrement
	 * */
	/*Syntax :
	 * for(Initialization;Condition;Increment/Decrement){
	 * 			statement ;
	 * }
	 * */
		for(int i=0;i<10;i++) {
			System.out.println(i); // it will print from 0 to 9
			
		}
}
}
