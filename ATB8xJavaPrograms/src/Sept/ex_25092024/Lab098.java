package Sept.ex_25092024;

public class Lab098 {
	
	public static void main(String[] args) {
		
		//For loop with other data_types
		//Numerical data_types are supported 
		//String an boolean are not supported
		for (float f=0.5f;f<10.67;f++) {
			System.out.println(f); //0.5 ,1.5....10.5
		}
		
		for (byte b=0;b<10.67;b++) {
			System.out.println(b); //0 to 10
		}
		
		for (long i=1;i<10;i++) {
			System.out.println(i); // 1 to 9
		}
	}
}
